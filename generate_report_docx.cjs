// ----- helpers
function t(text, opts = {}) {
  return new TextRun({
    text: String(text),
    font: { name: FONT, hint: 'default' },
    size: opts.size || 22, // half-points; 22 = 11pt
    bold: !!opts.bold,
    italics: !!opts.italics,
    color: opts.color || '000000',
  });
}
function p(text, opts = {}) {
  const runs = Array.isArray(text) ? text : [t(text, opts)];
  return new Paragraph({
    children: runs,
    alignment: opts.alignment || AlignmentType.LEFT,
    spacing: { before: opts.before || 80, after: opts.after || 80, line: 320 },
  });
}
function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 360, after: 180 },
    children: [new TextRun({ text, font: FONT, size: 32, bold: true, color: '1F3864' })],
  });
}
function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 240, after: 120 },
    children: [new TextRun({ text, font: FONT, size: 28, bold: true, color: '2E74B5' })],
  });
}
function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    spacing: { before: 200, after: 100 },
    children: [new TextRun({ text, font: FONT, size: 24, bold: true, color: '2E74B5' })],
  });
}
function bullet(text, level = 0) {
  return new Paragraph({
    children: [t(text)],
    bullet: { level },
    spacing: { before: 60, after: 60, line: 320 },
  });
}
function pageBreak() {
  return new Paragraph({ children: [new PageBreak()] });
}

const thinBorder = { style: BorderStyle.SINGLE, size: 4, color: '888888' };
const headerShading = { type: ShadingType.SOLID, color: 'D9E2F3' };

function tableCell(text, opts = {}) {
  const isHeader = !!opts.header;
  const para = new Paragraph({
    children: [
      new TextRun({
        text: String(text), font: FONT,
        size: isHeader ? 22 : 20, bold: isHeader,
      }),
    ],
    alignment: opts.alignment || AlignmentType.LEFT,
    spacing: { before: 30, after: 30 },
  });
  const cellOpts = {
    children: [para],
    shading: isHeader ? headerShading : undefined,
  };
  if (typeof opts.widthPct === 'number') {
    cellOpts.width = { size: opts.widthPct, type: WidthType.PERCENTAGE };
  }
  return new TableCell(cellOpts);
}

function tableFromRows(headers, rows, columnWidths) {
  const widthPct = (i) => {
    if (!columnWidths) return undefined;
    const w = columnWidths[i];
    return typeof w === 'number' ? w : (w && typeof w === 'object' ? w.size : undefined);
  };
  const headerRow = new TableRow({
    tableHeader: true,
    children: headers.map((h, i) => tableCell(h, {
      header: true, alignment: AlignmentType.CENTER,
      widthPct: widthPct(i),
    })),
  });
  const dataRows = rows.map(r => new TableRow({
    children: r.map((c, i) => tableCell(c, {
      widthPct: widthPct(i),
      alignment: i === 0 ? AlignmentType.LEFT : AlignmentType.CENTER,
    })),
  }));
  return new Table({
    rows: [headerRow, ...dataRows],
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: thinBorder, bottom: thinBorder, left: thinBorder, right: thinBorder,
      insideHorizontal: thinBorder, insideVertical: thinBorder,
    },
  });
}

